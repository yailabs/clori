static int fixture_write(char *path)
{
    int descriptor = mkstemp(path);
    size_t offset = 0u;
    if (descriptor < 0) return 0;
    while (offset < sizeof(png_fixture)) {
        ssize_t consumed = write(descriptor, png_fixture + offset, sizeof(png_fixture) - offset);
        if (consumed <= 0) {
            close(descriptor);
            unlink(path);
            return 0;
        }
        offset += (size_t)consumed;
    }
    return close(descriptor) == 0;
}

int yvex_test_image(void)
{
    char path[] = "/tmp/yvex-image-unit.XXXXXX";
    yvex_image decoded = {0}, stretch = {0}, cover = {0}, bicubic = {0}, refused = {0};
    yvex_image_resize_request request = {0};
    yvex_error err;

    YVEX_TEST_ASSERT(fixture_write(path), "create independent PNG fixture");
    YVEX_TEST_ASSERT(
        yvex_image_decode_file(&decoded, path, 1024u, &err) == YVEX_OK &&
            decoded.complete && decoded.width == 4u && decoded.height == 3u &&
            decoded.channels == 3u && decoded.data_bytes == 36u,
        "decode bounded RGB PNG with typed identity");
    request.schema_version = YVEX_IMAGE_RESIZE_SCHEMA_V1;
    request.resized_width = request.output_width = 7u;
    request.resized_height = request.output_height = 5u;
    YVEX_TEST_ASSERT(
        yvex_image_resize_lanczos_rgb8(&decoded, &request, &stretch, &err) == YVEX_OK &&
            stretch.complete && stretch.data_bytes == sizeof(stretch_oracle) &&
            memcmp(stretch.data, stretch_oracle, sizeof(stretch_oracle)) == 0,
        "LANCZOS stretch is pixel-identical to Pillow 11.3.0");
    request.resized_width = 8u;
    request.resized_height = 6u;
    request.crop_left = request.crop_top = 1u;
    request.output_width = 6u;
    request.output_height = 4u;
    YVEX_TEST_ASSERT(
        yvex_image_resize_lanczos_rgb8(&decoded, &request, &cover, &err) == YVEX_OK &&
            cover.complete && cover.data_bytes == sizeof(cover_oracle) &&
            memcmp(cover.data, cover_oracle, sizeof(cover_oracle)) == 0,
        "LANCZOS resize then crop is pixel-identical to Pillow 11.3.0");
    request.resized_width = request.output_width = 7u;
    request.resized_height = request.output_height = 5u;
    request.crop_left = request.crop_top = 0u;
    YVEX_TEST_ASSERT(
        yvex_image_resize_bicubic_rgb8(&decoded, &request, &bicubic, &err) == YVEX_OK &&
            bicubic.complete && bicubic.data_bytes == sizeof(bicubic_oracle) &&
            memcmp(bicubic.data, bicubic_oracle, sizeof(bicubic_oracle)) == 0,
        "BICUBIC vision resize is pixel-identical to Pillow 11.3.0");
    YVEX_TEST_ASSERT(
        yvex_image_decode_file(&refused, path, 32u, &err) == YVEX_ERR_BOUNDS &&
            !refused.complete && refused.data == NULL,
        "oversized image refuses without publication");
    yvex_image_close(&cover);
    yvex_image_close(&bicubic);
    yvex_image_close(&stretch);
    yvex_image_close(&decoded);
    unlink(path);
    return 0;
}
